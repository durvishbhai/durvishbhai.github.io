-- Payment receipts (KIS-PR-YYYY-NNNN). One row per receipt: made by the system when a payment is confirmed, or by the team by hand for a payment made outside.
-- The client's details and the amounts are frozen on the row, and `seal` is a keyed hash of the important facts so the public verification page can tell a genuine,
-- untouched receipt from an edited one. A receipt is never edited or deleted; it can only be voided with a reason.
CREATE TABLE receipts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(32) NOT NULL,
    number VARCHAR(30) NOT NULL,
    verify_code CHAR(12) NOT NULL,
    source ENUM('client_payment','renewal_payment','manual') NOT NULL,
    source_id BIGINT UNSIGNED NULL,
    external_key CHAR(64) NOT NULL,
    client_id BIGINT UNSIGNED NULL,
    client_snapshot TEXT NOT NULL,
    method VARCHAR(40) NOT NULL,
    txn_id VARCHAR(120) NOT NULL,
    paid_at DATETIME NOT NULL,
    time_known TINYINT(1) NOT NULL DEFAULT 1,
    lines_json TEXT NOT NULL,
    subtotal_minor BIGINT UNSIGNED NOT NULL,
    discount_minor BIGINT UNSIGNED NOT NULL DEFAULT 0,
    tax_minor BIGINT UNSIGNED NOT NULL DEFAULT 0,
    paid_minor BIGINT UNSIGNED NOT NULL,
    against VARCHAR(160) NULL,
    note VARCHAR(300) NULL,
    status ENUM('valid','void') NOT NULL DEFAULT 'valid',
    void_reason VARCHAR(255) NULL,
    voided_by BIGINT UNSIGNED NULL,
    voided_at DATETIME NULL,
    seal CHAR(64) NOT NULL,
    issued_by BIGINT UNSIGNED NULL,
    issued_at DATETIME NOT NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_receipts_public (public_id),
    UNIQUE KEY uq_receipts_number (number),
    UNIQUE KEY uq_receipts_code (verify_code),
    UNIQUE KEY uq_receipts_external (external_key),
    KEY idx_receipts_client (client_id, issued_at),
    KEY idx_receipts_source (source, source_id),
    CONSTRAINT fk_receipts_client FOREIGN KEY (client_id) REFERENCES clients (id) ON DELETE SET NULL,
    CONSTRAINT fk_receipts_issued_by FOREIGN KEY (issued_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_receipts_voided_by FOREIGN KEY (voided_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
